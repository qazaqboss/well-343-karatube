#!/usr/bin/env bash
# Генерация OG-баннеров 1200×630 из tools/og-template.html.
# Запуск из корня репозитория:  ./tools/make-og.sh
set -e

CHROME="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
[ -x "$CHROME" ] || CHROME="$(command -v chromium || command -v google-chrome)"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TPL="file://$ROOT/tools/og-template.html"
OUT="$ROOT/public"

shot () { # shot <файл> <строка запроса>
  "$CHROME" --headless --disable-gpu --hide-scrollbars \
    --window-size=1200,630 --virtual-time-budget=4000 \
    --screenshot="$OUT/$1" "$TPL?$2" 2>/dev/null
  echo "  $1"
}

enc () { python3 -c "import urllib.parse,sys;print(urllib.parse.quote(sys.argv[1]))" "$1"; }

echo "Генерирую баннеры:"

# ── Главная и продукт: сам состав ───────────────────────────────────────────
shot "og-main.png" "mark=UT-9\
&eyebrow=$(enc 'ТОО «ЭкоМикс» · EASYMIX · изоляция водопритока')\
&title=$(enc 'NANOCEM UT-9')\
&sub=$(enc 'Ультратонкая изоляционно-инъекционная смесь для изоляции водопритока. Помол D95 ≤ 9 мкм — входит туда, куда обычный цемент не проходит.')\
&stats=$(enc 'Тонкость помола|D95 ≤ 9 мкм;;Прочность 28 сут|65–75 МПа;;Опорный кейс|1,1 → 16,4 т/сут')"

# ── Фонд скважин: запасной вариант баннера для главной ───────────────────────
# Сейчас главная отдаёт og-main.png (продукт). Чтобы показать платформу —
# поменяйте og:image и twitter:image в public/index.html на og-fund.png.
shot "og-fund.png" "mark=J1-IV\
&eyebrow=$(enc 'Горизонт J1-IV · суточный мониторинг')\
&title=$(enc 'АНАЛИТИКА ФОНДА<br><span class=\"light\">И</span> НЕДРОПОЛЬЗОВАНИЕ')\
&size=76\
&sub=$(enc 'Суточный мониторинг шести скважин, изоляция водопритока NanoCem UT-9 и семь этапов недропользования — на одной площадке.')\
&stats=$(enc 'Скважин под мониторингом|6;;Кандидатов в программе|22;;Этапов недропользования|7')"

# ── Герметичность ───────────────────────────────────────────────────────────
shot "og-sealing.png" "mark=АКЦ\
&eyebrow=$(enc 'Аналитика · Заходы NanoCem UT-9')\
&title=$(enc 'ГЕРМЕТИЧНОСТЬ<br>ФОНДА')\
&size=86\
&sub=$(enc 'Где изоляция держит и почему иногда нет: разбор шести заходов, география отказов и заколонный переток по данным АКЦ/ЭМДС.')\
&stats=$(enc 'Заходов UT-9|6 скважин;;Герметично с 1-го|3;;Опорный кейс|Скв. 343')"

# ── Программа ───────────────────────────────────────────────────────────────
shot "og-plan.png" "mark=UT-9\
&eyebrow=$(enc 'Программа применения · II полугодие 2026')\
&title=$(enc 'ПОРТФЕЛЬ<br>КАНДИДАТОВ')\
&size=86\
&sub=$(enc 'Двадцать две скважины под изоляцию водопритока: три сценария применения, волны заходов и объекты изоляции.')\
&stats=$(enc 'Кандидатов|22;;Прямой ЦПД|12 скважин;;Период|Авг — ноя 2026')"

# ── Этапы недропользования ──────────────────────────────────────────────────
shot "og-stages.png" "mark=1—7\
&eyebrow=$(enc 'Недропользование РК · Кодекс о недрах')\
&title=$(enc 'СЕМЬ ЭТАПОВ<br><span class=\"light\">НЕДРОПОЛЬЗОВАНИЯ</span>')\
&size=72\
&sub=$(enc 'От разведки до сдачи контрактной территории: документы, сроки и отчёт, который нужно выпустить на каждом этапе.')\
&stats=$(enc 'Этапов|7;;Подготовительный|≤ 3 лет;;Полномасштабная добыча|≤ 25 лет')"

# ── Баннеры по скважинам ────────────────────────────────────────────────────
# Цифры берутся из public/wells.js — при обновлении фонда поправьте и здесь.
well () {   # well <номер> <статус> <Qн> <обв> <примечание>
  shot "og-$1.png" "mark=$(enc "$1")\
&eyebrow=$(enc 'Суточный мониторинг · NanoCem UT-9')\
&title=$(enc "СКВАЖИНА <span class=\"light\">№</span>$1")\
&size=92\
&sub=$(enc "$5")\
&stats=$(enc "Статус|$2;;Qн на 27.09|$3 т/сут;;Обводнённость|$4")"
}

well 343 "В работе · 150 об/мин" "10,61" "48,1%" \
  "Опорный кейс изоляции водопритока: дебит вырос с 1,10 до 16,40 т/сут на пике. Эффект держится восьмой месяц."
well 342 "В работе · 160 об/мин" "7,86"  "37,1%" \
  "Герметично со второго захода. За сентябрь дебит вырос на 13% при снижении обводнённости."
well 301 "В работе · 150 об/мин" "10,28" "37,1%" \
  "Второй ровный месяц подряд: обводнённость в коридоре 37–39%, без остановок."
well 303 "В работе с 11.09"      "2,78"  "65,4%" \
  "После ТРС вышла на 2,86 т/сут — лучший результат за всю историю наблюдений."
well 305 "В работе с 08.09"      "1,42"  "18,6%" \
  "После ГРП переведена на вышележащий горизонт. Работает почти безводно, но отдача низкая."
well 311 "В работе · 110 об/мин" "6,31"  "60,1%" \
  "Эффект изоляции подтверждён после освоения: обводнённость с 90,5% до 60%."

echo "Готово. Файлы в public/"
