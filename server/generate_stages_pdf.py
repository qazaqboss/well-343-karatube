def stage_page(pdf: PDF, stage: dict):
    pdf.add_page()
    c  = stage["color"]
    cl = stage["color_light"]
    pdf._cur_stage_name = f"Этап {stage['num']} — {stage['name']}"

    # Цветная шапка
    pdf.set_fill_color(*c)
    pdf.rect(0, 0, 210, 30, "F")
    pdf.set_fill_color(*ACC)
    pdf.rect(0, 30, 210, 3, "F")

    pdf.set_xy(0, 7)
    pdf.set_font("U", "B", 20)
    pdf.set_text_color(*WH)
    pdf.cell(0, 9, f"  ЭТАП {stage['num']}: {stage['name'].upper()}", ln=True)
    pdf.set_font("U", "", 9)
    pdf.set_text_color(210, 230, 255)
    pdf.cell(0, 5, f"  {stage['en']}  |  Срок: {stage['max_years']}", ln=True)
    pdf.set_text_color(*BK)
    pdf.ln(10)

    # Описание этапа
    pdf.set_font("U", "", 9)
    pdf.set_text_color(*GD)
    pdf.multi_cell(174, 5, stage["description"])
    pdf.ln(3)

    # Примечание (если нет паспортов)
    if "note" in stage:
        pdf.set_fill_color(255, 248, 220)
        pdf.set_xy(18, pdf.get_y())
        pdf.rect(18, pdf.get_y(), 174, 12, "F")
        pdf.set_xy(20, pdf.get_y() + 2)
        pdf.set_font("U", "B", 8.5)
        pdf.set_text_color(*OR)
        pdf.cell(0, 4, "Примечание по паспортам скважин:", ln=True)
        pdf.set_xy(20, pdf.get_y())
        pdf.set_font("U", "", 8.5)
        pdf.set_text_color(*GD)
        pdf.multi_cell(170, 4.5, stage["note"])
        pdf.ln(3)

    # Таблица документов
    pdf.h2(f"Перечень документов — Этап {stage['num']}", c=tuple(c))
    headers = ["Документ", "Срок", "Орган", "Обяз.", "НПА"]
    widths  = [62, 32, 38, 12, 30]
    pdf.set_fill_color(*DB)
    pdf.set_text_color(*WH)
    pdf.set_font("U", "B", 7.5)
    for h, w in zip(headers, widths):
        pdf.cell(w, 6, h, align="C", fill=True)
    pdf.ln()

    for i, doc in enumerate(stage["docs"]):
        bg = tuple(cl) if i % 2 == 0 else WH
        pdf.set_fill_color(*bg)
        pdf.set_font("U", "B" if doc.get("is_passport") else "", 7.5)
        pdf.set_text_color(*tuple(c) if doc.get("is_passport") else GD)
        pdf.cell(62, 5.5, doc["name"][:55], fill=True)
        pdf.set_font("U", "", 7)
        pdf.set_text_color(*GD)
        pdf.cell(32, 5.5, doc["deadline"][:30], fill=True)
        pdf.cell(38, 5.5, doc["authority"][:34], fill=True)
        pdf.set_font("U", "B", 8)
        pdf.set_text_color(*(GRN if doc["required"] else OR))
        pdf.cell(12, 5.5, "Да" if doc["required"] else "Нет*", fill=True, align="C")
        pdf.set_font("U", "", 7)
        pdf.set_text_color(*MB)
        refs_str = ", ".join([f"[{REGS[r]['short'].split()[-1]}]" for r in doc["refs"][:3]])
        pdf.cell(30, 5.5, refs_str, fill=True)
        pdf.ln()
    pdf.set_font("U", "I", 7)
    pdf.set_text_color(130, 130, 130)
    pdf.cell(0, 4, "  * — обязателен при наступлении соответствующего условия", ln=True)
    pdf.ln(2)

    # НПА ссылки
    all_refs = []
    for doc in stage["docs"]:
        for r in doc["refs"]:
            if r not in all_refs:
                all_refs.append(r)

    pdf.h2("Нормативные ссылки этапа", c=(60, 100, 160))
    for key in all_refs:
        pdf.ref_badge(key)
    pdf.ln(2)


def passport_template(pdf: PDF, stage: dict, ptype: str):
    """Генерирует шаблон паспорта скважины для данного этапа."""
    pdf.add_page()
    c = stage["color"]
    pdf._cur_stage_name = f"Паспорт скважины — Этап {stage['num']}"

    # Шапка
    pdf.set_fill_color(*c)
    pdf.rect(0, 0, 210, 26, "F")
    pdf.set_fill_color(*DB)
    pdf.rect(0, 26, 210, 7, "F")
    pdf.set_xy(0, 5)
    pdf.set_font("U", "B", 14)
    pdf.set_text_color(*WH)
    pdf.cell(0, 7, f"  ПАСПОРТ СКВАЖИНЫ — ЭТАП {stage['num']}: {stage['name'].upper()}", ln=True)
    pdf.set_font("U", "", 8.5)
    pdf.set_text_color(210, 230, 255)
    pdf.cell(0, 5, f"  Тип: {stage['passport_type']}", ln=True)
    pdf.set_xy(0, 27)
    pdf.set_font("U", "B", 7.5)
    pdf.set_text_color(*WH)
    refs_str = "  НПА: " + "  |  ".join([REGS[r]["short"] for r in stage["passport_refs"]])
    pdf.cell(0, 6, refs_str[:130])
    pdf.set_text_color(*BK)
    pdf.ln(12)

    # Типы скважин
    if stage["well_types"]:
        pdf.set_fill_color(*LB)
        pdf.set_text_color(*DB)
        pdf.set_font("U", "B", 8)
        pdf.cell(0, 5.5, "  Применяется для типов скважин:", fill=True, ln=True)
        for wt in stage["well_types"]:
            pdf.set_font("U", "", 8)
            pdf.set_text_color(*GD)
            pdf.cell(8, 5, "")
            pdf.cell(0, 5, f"  -  {wt}", ln=True)
        pdf.ln(2)

    # Секции паспорта
    sections = PASSPORT_SECTIONS.get(ptype, PASSPORT_SECTIONS["exploration"])
    for sec_name, fields in sections:
        pdf.h3(sec_name, c=LB)
        for field in fields:
            pdf.set_font("U", "", 8.5)
            pdf.set_text_color(*GD)
            pdf.cell(6, 5.5, "")
            pdf.set_font("U", "B", 8)
            pdf.set_text_color(*DB)
            # Поле ввода: название + линия для заполнения
            pdf.cell(65, 5.5, field + ":")
            pdf.set_fill_color(250, 252, 255)
            pdf.set_draw_color(180, 200, 230)
            pdf.rect(pdf.get_x(), pdf.get_y() + 0.5, 96, 4.5, "FD")
            pdf.cell(96, 5.5, "", border=0)
            pdf.ln()
        pdf.ln(1)

    # Подписи
    pdf.ln(2)
    pdf.h3("ПОДПИСИ И ПЕЧАТИ", c=(220, 235, 255))
    sig_parties = [
        ("Оператор / Недропользователь",    "Главный геолог:"),
        ("Буровой подрядчик",               "Ответственный руководитель:"),
        ("Геофизический подрядчик",         "Представитель:"),
        ("Тампонажный подрядчик",           "Представитель:"),
    ]
    for party, role in sig_parties:
        pdf.set_font("U", "B", 8)
        pdf.set_text_color(*DB)
        pdf.cell(55, 5, party + ":")
        pdf.set_font("U", "", 8)
        pdf.set_text_color(*GD)
        pdf.cell(35, 5, role)
        pdf.set_draw_color(*MB)
        pdf.cell(60, 5, "_" * 35)
        pdf.cell(24, 5, f"Дата: ___.___.____")
        pdf.ln(7)

    # НПА ссылки внизу
    pdf.ln(2)
    pdf.divider()
    pdf.set_font("U", "B", 8)
    pdf.set_text_color(*DB)
    pdf.cell(0, 5, "Нормативная база паспорта:", ln=True)
    pdf.ln(1)
    for key in stage["passport_refs"]:
        r = REGS[key]
        pdf.set_font("U", "B", 7.5)
        pdf.set_text_color(*MB)
        pdf.cell(35, 5, f"[{r['short']}]")
        pdf.set_font("U", "", 7.5)
        pdf.set_text_color(*GD)
        pdf.cell(80, 5, r["topic"])
        pdf.set_font("U", "I", 7)
        pdf.set_text_color(100, 120, 180)
        pdf.cell(59, 5, r["url"][:45], ln=True)
    pdf.ln(1)


