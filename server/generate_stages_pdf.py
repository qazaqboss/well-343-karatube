class PDF(FPDF):
    def __init__(self):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.set_auto_page_break(True, margin=18)
        self.set_margins(18, 14, 18)
        self.add_font("U", "",  fname=FONT)
        self.add_font("U", "B", fname=FONT)
        self.add_font("U", "I", fname=FONT)
        self.set_font("U", "", 9)
        self._cur_stage_name = ""

    def header(self):
        if self.page_no() == 1:
            return
        self.set_fill_color(*DB)
        self.rect(0, 0, 210, 7, "F")
        self.set_xy(18, 1.5)
        self.set_font("U", "B", 6.5)
        self.set_text_color(*WH)
        self.cell(0, 4, f"IC Petroleum  |  Документы недропользователя РК  |  {self._cur_stage_name}")
        self.set_text_color(*BK)
        self.ln(8)

    def footer(self):
        self.set_y(-12)
        self.set_fill_color(*DB)
        self.rect(0, self.get_y(), 210, 14, "F")
        self.set_font("U", "", 6.5)
        self.set_text_color(*WH)
        self.cell(0, 8,
            f"IC Petroleum LLP  |  Конфиденциально  |  {datetime.now().strftime('%d.%m.%Y')}  |  Стр. {self.page_no()}",
            align="C")

    def h1(self, t):
        self.set_fill_color(*DB)
        self.set_text_color(*WH)
        self.set_font("U", "B", 12)
        self.cell(174, 8, f"  {t}", fill=True, ln=True)
        self.set_text_color(*BK)
        self.ln(2)

    def h2(self, t, c=MB):
        self.set_fill_color(*c)
        self.set_text_color(*WH)
        self.set_font("U", "B", 9.5)
        self.cell(174, 7, f"  {t}", fill=True, ln=True)
        self.set_text_color(*BK)
        self.ln(1.5)

    def h3(self, t, c=LB):
        self.set_fill_color(*c)
        self.set_text_color(*DB)
        self.set_font("U", "B", 8.5)
        self.cell(174, 6, f"  {t}", fill=True, ln=True)
        self.set_text_color(*BK)
        self.ln(1)

    def body(self, t, indent=0):
        self.set_font("U", "", 8.5)
        self.set_text_color(*GD)
        if indent:
            self.set_x(self.get_x() + indent)
        self.multi_cell(174 - indent, 5, t)
        self.set_text_color(*BK)

